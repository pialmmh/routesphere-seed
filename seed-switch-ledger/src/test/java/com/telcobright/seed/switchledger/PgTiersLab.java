package com.telcobright.seed.switchledger;

import java.io.IOException;
import java.net.InetSocketAddress;
import java.net.Socket;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

/**
 * A throwaway PostgreSQL of a round (trust on loopback: no password exists; {@code SWITCH_LEDGER_LAB_PG} = host:port, 127.0.0.1:7453 unless
 * said) holding ONE database with a root's tiers as schemas — each with the two tables the embedded switch ledger caches, as prime-context's
 * PostgreSQL schema makes them (the lines of seed-prepaid's {@code PostgresPurchaseLab}). Nothing listening there: the tests that need it
 * are skipped, said in words.
 */
public final class PgTiersLab {

    public static final String DATABASE = "switch_ledger_lab";
    private static final String USER = "postgres";
    private static final String ADDRESS = System.getenv().getOrDefault("SWITCH_LEDGER_LAB_PG", "127.0.0.1:7453");

    private static final String PACKAGEACCOUNT =
        "create table packageaccount (id_packageaccount bigint generated by default as identity, balanceAfter numeric(20,6) not null, balanceBefore numeric(20,6) not null,"
            + " id_PackagePurchase bigint not null, lastAmount numeric(20,6) not null, name varchar(255), uom varchar(255) not null, creditLimit numeric(20,6),"
            + " isSelected boolean not null default false, id_packageitem bigint, primary key (id_packageaccount))";
    private static final String PACKAGEACCOUNTRESERVE =
        "create table packageaccountreserve (channel_call_uuid varchar(255) not null, id_packageaccount bigint not null, id_PackagePurchase bigint not null,"
            + " name varchar(255), reserveUnit numeric(20,6), time varchar(255), uom varchar(255), primary key (channel_call_uuid))";

    private PgTiersLab() {}

    /** Null = here; else why the lab is not (nothing listens on its address). */
    public static String absentBecause() {
        String[] hostPort = ADDRESS.split(":");
        try (Socket s = new Socket()) {
            s.connect(new InetSocketAddress(hostPort[0], Integer.parseInt(hostPort[1])), 500);
            return null;
        } catch (IOException e) {
            return "no lab PostgreSQL here: nothing listens on " + ADDRESS + " (SWITCH_LEDGER_LAB_PG)";
        }
    }

    public static String url() { return "jdbc:postgresql://" + ADDRESS + "/" + DATABASE; }

    public static String user() { return USER; }

    /** A new session on the lab's database (a plain JDBC session: what another process would hold). */
    public static Connection connect() throws SQLException { return DriverManager.getConnection(url(), USER, null); }

    /** The database made again, empty: each tier a schema with the two tables. */
    public static void freshTiers(List<String> tiers) throws SQLException {
        try (Connection admin = DriverManager.getConnection("jdbc:postgresql://" + ADDRESS + "/postgres", USER, null); Statement s = admin.createStatement()) {
            s.execute("DROP DATABASE IF EXISTS " + DATABASE + " WITH (FORCE)");
            s.execute("CREATE DATABASE " + DATABASE);
        }
        try (Connection c = connect(); Statement s = c.createStatement()) {
            for (String tier : tiers) {
                s.execute("CREATE SCHEMA " + tier);
                s.execute("SET search_path TO " + tier);
                s.execute(PACKAGEACCOUNT);
                s.execute(PACKAGEACCOUNTRESERVE);
            }
        }
    }

    /** A condition the lab waits for (at most 20 s, every 100 ms); not met = the test fails, naming it. */
    public static void await(String what, Condition condition) throws Exception {
        long until = System.nanoTime() + 20_000_000_000L;
        while (!condition.met()) {
            if (System.nanoTime() > until) throw new AssertionError("not within 20 s: " + what);
            Thread.sleep(100);
        }
    }

    /** What the lab waits for. */
    @FunctionalInterface
    public interface Condition { boolean met() throws Exception; }

    /**
     * recall-db's bookmark lock, taken exactly as recall-db takes it (master 5534e69, {@code InstanceLock.take}/{@code tryLock}):
     * {@code SELECT pg_try_advisory_lock(hashtext('recall-db-bookmark:' || <first schema>))} on {@code session}. True = taken.
     */
    public static boolean takeTheBookmarkLockAsRecallDb(Connection session, String firstSchema) throws SQLException {
        try (PreparedStatement ps = session.prepareStatement("SELECT pg_try_advisory_lock(hashtext(?))")) {
            ps.setString(1, "recall-db-bookmark:" + firstSchema);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() && rs.getBoolean(1);
            }
        }
    }
}
